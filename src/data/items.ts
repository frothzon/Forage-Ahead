export type ItemCategory =
  | 'material'
  | 'food'
  | 'tool'
  | 'weapon'
  | 'armor'
  | 'accessory'
  | 'relic'
  | 'gadget'
  | 'consumable';

export type ItemRarity = 'common' | 'uncommon' | 'rare' | 'epic' | 'relic';
export type EquipSlot = 'weapon' | 'tool' | 'armor' | 'accessory';

export interface GearStats {
  attack?: number;
  gather?: number;
  armor?: number;
  critPct?: number;
  speedPct?: number;
  maxHp?: number;
  maxEnergy?: number;
}

