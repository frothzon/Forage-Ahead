export function generatePixelArtIcons(outDir, manifest) {
  fs.mkdirSync(outDir, { recursive: true });
  for (const [name, spec] of Object.entries(SPRITES)) {
    const { width, height, rgba } = renderGrid(spec.rows, spec.palette);
    const png = encodePng(width, height, rgba);
    const file = `${name}.png`;
    fs.writeFileSync(path.join(outDir, file), png);
    manifest.images[`ui_icons/${name}`] = {
      path: `assets/ui_icons/${file}`,
      width,
      height,
    };
  }
}
